import jwt from "jsonwebtoken";
import { createHash } from "node:crypto";

const JWT_SECRET = process.env.JWT_SECRET!;
const TOKEN_EXPIRY = "12h"; // NFR-008: end session after 12 hours

export function signToken(user_id: number){
  return jwt.sign({ user_id }, JWT_SECRET, { expiresIn: TOKEN_EXPIRY });
}

export function verifyToken(token: string) {
  return jwt.verify(token, JWT_SECRET) as { user_id: number };
}

// ---------- Password reset tokens ----------

// NFR-009: reset token expires after 15 minutes (NFR-008: end session after 12 hours)
const RESET_SECRET = `${JWT_SECRET}:password-reset`;
const RESET_TOKEN_EXPIRY = "15m";

// NFR-010: password reset tokens can only be used once
// To achieve this, we include a fingerprint of the user's current password hash in the reset token. When the user resets their password, the fingerprint is checked against the current password hash. If they don't match, the token is considered invalid (because it has already been used to reset the password). The fingerprint is generated by hashing the password hash with SHA-256 and then taking the first 16 characters.
function passwordFingerprint(password_hash: string) {
  return createHash("sha256").update(password_hash).digest("hex").slice(0, 16);
}

export function signResetToken(user_id: number, password_hash: string) {
  return jwt.sign(
    { user_id, pwd: passwordFingerprint(password_hash) },
    RESET_SECRET,
    { expiresIn: RESET_TOKEN_EXPIRY }
  );
}

export function verifyResetToken(token: string) {
  return jwt.verify(token, RESET_SECRET) as { user_id: number; pwd: string };
}

export function matchesPasswordFingerprint(pwd: string, password_hash: string) {
  return pwd === passwordFingerprint(password_hash);
}
